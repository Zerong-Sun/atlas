function kit(
  id: string,
  sampleQuestions: string[],
  modeLabels: string[],
  symbolNames: string[],
  samplePattern: string
): MethodModuleKit {
  return {
    id,
    sampleQuestions,
    modes: modeLabels.map((label, index) => ({
      id: `${id}-mode-${index + 1}`,
      label,
      description: getModeDescription(label, index),
    })),
    symbolLexicon: symbolNames.map((name, index) => ({
      name,
      meaning: getSymbolMeaning(name, index),
      prompt: getSymbolPrompt(name),
    })),
    samplePattern,
    resultAdvice: [
      "先把问题收窄成一个可行动的主题，再看象征是否指向同一方向。",
      "把结果当作整理材料的镜子，优先执行低风险、可验证的小步骤。",
      "若结论让你焦虑，暂停重问，改用记录、复盘或现实咨询来校准。",
    ],
    artifactLabels: ["本次主象", "辅助线索", "行动提醒"],
  };
}

function getModeDescription(label: string, index: number) {
  const descriptions = [
    "适合快速开始，用最少输入生成一个可复盘的结果。",
    "适合正式解读，会保留更多过程和象征层次。",
    "适合对比与追问，把结果整理成后续可扩展素材。",
  ];
  return `${label}：${descriptions[index] ?? descriptions[0]}`;
}

function getSymbolMeaning(name: string, index: number) {
  const meanings = [
    "代表事情的主轴和最先需要看见的力量。",
    "代表环境条件、他人影响或当前可借用的资源。",
    "代表阻力、转折或需要谨慎处理的边界。",
    "代表可以主动调整的策略和表达方式。",
    "代表后续复盘时值得持续观察的信号。",
  ];
  return `${name}：${meanings[index] ?? meanings[0]}`;
}

function getSymbolPrompt(name: string) {
  return `当「${name}」出现时，询问它是在提示机会、阻力、节奏，还是需要被重新命名的感受。`;
}

export function getMethodModuleKit(id: string | undefined) {
  return METHOD_MODULE_KITS.find((kitItem) => kitItem.id === id);
}
