"""Import public-domain Zhouyi primary text, with Wikisource revision provenance.
Run from any directory. Only imports 经/大象/六爻, never modern commentary.
"""
import urllib.request, urllib.parse, json, re, pathlib, hashlib
ROOT=pathlib.Path(__file__).resolve().parents[1]
NAMES='乾 坤 屯 蒙 需 訟 師 比 小畜 履 泰 否 同人 大有 謙 豫 隨 蠱 臨 觀 噬嗑 賁 剝 復 无妄 大畜 頤 大過 坎 離 咸 恒 遯 大壯 晉 明夷 家人 睽 蹇 解 損 益 夬 姤 萃 升 困 井 革 鼎 震 艮 漸 歸妹 豐 旅 巽 兌 渙 節 中孚 小過 既濟 未濟'.split()
def clean(s):
 s=re.sub(r'<[^>]*>', '', s)
 s=re.sub(r'\{\{另\|([^|{}]+)\|[^{}]+\}\}',r'\1',s)
 s=re.sub(r'\{\{\*\|([^{}]*)\}\}',r'（\1）',s)
 s=re.sub(r'-\{([^{}]+)\}-',r'\1',s)
 s=s.replace("'''",'').replace("''",'')
 return s.strip(' *#\n\t')
records={}
for start in range(0,64,25):
 query={'action':'query','prop':'revisions','rvprop':'ids|content','rvslots':'main','titles':'|'.join('周易/'+n for n in NAMES[start:start+25]),'format':'json','redirects':1}
 url='https://zh.wikisource.org/w/api.php?'+urllib.parse.urlencode(query)
 data=json.load(urllib.request.urlopen(urllib.request.Request(url,headers={'User-Agent':'AtlasCultureAudit/1.0'}),timeout=45))
 for p in data['query']['pages'].values():
  revision=p['revisions'][0]; raw=revision['slots']['main']['*']; name=p['title'].split('/')[-1]
  part=raw[raw.index('易經'):]; part=part.split('彖曰')[0]
  judgments=[]; yaos=[]
  for line in part.splitlines():
   if line.startswith('*#'):yaos.append(clean(line))
   elif line.startswith('**'):judgments.append(clean(line))
  judgment=''.join(judgments); judgment=judgment.split('：',1)[-1]
  imagepart=raw[raw.index('象曰'):]; image=''.join(clean(l) for l in imagepart.split('*#')[0].splitlines() if l.startswith('**'))
  if len(yaos)<6 or not judgment or not image or '{{' in judgment+image+''.join(yaos):
   raise ValueError((name,len(yaos),judgment,image))
  records[NAMES.index(name)+1]={'name':name,'judgment':judgment,'image':image,'yaoTexts':yaos[:6],'useText':yaos[6] if len(yaos)>6 else None,'sourceUrl':'https://zh.wikisource.org/w/index.php?oldid='+str(revision['revid']),'sourceTitle':'《周易》'+name+'卦 · 经文与大象','sourceRevision':revision['revid'],'sourceSha256':hashlib.sha256(raw.encode()).hexdigest(),'textKind':'primary-text','license':'Ancient original text: public domain; Wikisource transcription attribution retained; CC BY-SA 4.0 where applicable.'}
assert len(records)==64
out=ROOT/'packages/engines/src/data/iching-classics.json'
out.write_text(json.dumps(dict(sorted(records.items())),ensure_ascii=False,indent=2)+'\n')
(out.parent/'iching-classics.ts').write_text('// Generated by scripts/import-iching.py. Ancient primary text, with revision provenance.\nexport const ICHING_CLASSICS = '+json.dumps(dict(sorted(records.items())),ensure_ascii=False,indent=2)+' as const;\n')
print(f'{len(records)} hexagrams; {sum(len(r["yaoTexts"]) for r in records.values())} lines; written {out}')
