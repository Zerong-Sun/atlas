/** Generates an additive migration; never connects to a database. */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { CULTURE_LESSONS } from "../packages/method-data/src/cultureLessons.ts";
import { HEXAGRAMS, KING_WEN_BITS } from "../packages/engines/src/iching.ts";
const sql=(value:unknown)=>"'"+JSON.stringify(value).replace(/'/g,"''")+"'::jsonb";
const lines=[`-- Generated by scripts/export-culture-catalog.ts. Offline catalogue v2026-10-20.
-- User records, source_chunks, and historical readings are not rewritten.
begin;
create table if not exists public.iching_hexagrams (
 number smallint primary key check (number between 1 and 64),
 line_bits smallint not null unique check (line_bits between 0 and 63),
 payload jsonb not null check (jsonb_typeof(payload) = 'object'),
 content_version text not null default '2026-10-20'
);
create table if not exists public.culture_lessons (
 method_id text primary key,
 payload jsonb not null check (jsonb_typeof(payload) = 'object'),
 content_version text not null default '2026-10-20'
);
alter table public.iching_hexagrams enable row level security;
alter table public.culture_lessons enable row level security;
grant select on public.iching_hexagrams, public.culture_lessons to anon, authenticated;
revoke insert, update, delete on public.iching_hexagrams, public.culture_lessons from anon, authenticated;
drop policy if exists iching_catalog_read on public.iching_hexagrams;
create policy iching_catalog_read on public.iching_hexagrams for select to anon, authenticated using (true);
drop policy if exists culture_catalog_read on public.culture_lessons;
create policy culture_catalog_read on public.culture_lessons for select to anon, authenticated using (true);
`];
for(const [n,text] of Object.entries(HEXAGRAMS))lines.push(`insert into public.iching_hexagrams(number,line_bits,payload) values (${n},${KING_WEN_BITS[Number(n)-1]},${sql(text)}) on conflict (number) do update set line_bits=excluded.line_bits,payload=excluded.payload,content_version='2026-10-20';`);
for(const [id,lesson] of Object.entries(CULTURE_LESSONS))lines.push(`insert into public.culture_lessons(method_id,payload) values ('${id}',${sql(lesson)}) on conflict (method_id) do update set payload=excluded.payload,content_version='2026-10-20';`);
lines.push('commit;\n');
writeFileSync(fileURLToPath(new URL('../supabase/migrations/20261020000000_culture_catalog.sql',import.meta.url)),lines.join('\n'));
console.log(`${Object.keys(HEXAGRAMS).length} hexagrams and ${Object.keys(CULTURE_LESSONS).length} lessons; migration generated, not applied.`);
